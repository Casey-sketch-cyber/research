def opaque(value: object) -> str:
    """Keep joins deterministic without publishing original dataset identifiers."""
    return hashlib.sha256(str(value).encode()).hexdigest()[:16]


def clean_example(key: str, value: object) -> object:
    """Remove source-frame coordinates and identifiers from schema examples."""
    if pd.isna(value):
        return None
    if key.endswith("_id") or key == "id":
        return "id_" + opaque(value)
    if key == "geometry":
        geom = from_wkt(str(value))
        geom = affinity.translate(geom, xoff=-geom.bounds[0], yoff=-geom.bounds[1])
        return geom.wkt[:160] + ("..." if len(geom.wkt) > 160 else "")
    return value.item() if isinstance(value, np.generic) else value


def write_report(name: str, digest: str, sections: list[str]) -> None:
    """Write a deterministic research report, with its generating command."""
    Path(f"reports/schemas/{name}.md").write_text(
        f"# {name} schema inspection\n\nConfig hash: `{digest}`. Generated by `scripts/02_inspect_schemas.py`.\n\n"
        + "\n\n".join(sections) + "\n", encoding="utf-8")


def inspect_d1(root: Path, digest: str) -> None:
    """Count every geometry and simulation row and all observed D1 subtypes."""
    archive = root / "swiss_dwellings/swiss-dwellings-v3.0.0.zip"
    statistics, sections = {}, []
    subtype_counts = Counter()
    area_subtypes = Counter()
    residential_subtypes = Counter()
    opening_dimensions = defaultdict(list)
    for basename in ("geometries.csv", "simulations.csv"):
        path = extract_named(archive, basename, root / "swiss_dwellings/extracted" / basename)
        dtypes, count, examples = defaultdict(set), 0, []
        for chunk in tqdm(pd.read_csv(path, chunksize=50000, low_memory=False), desc=basename):
            count += len(chunk)
            for key, dtype in chunk.dtypes.items():
                dtypes[key].add(str(dtype))
            if not examples:
                examples = [{key: clean_example(key, value) for key, value in row.items()}
                            for row in chunk.head(5).to_dict("records")]
            if basename == "geometries.csv":
                subtype_counts.update(chunk.groupby(["entity_type", "entity_subtype"], dropna=False).size().to_dict())
                area_subtypes.update(chunk.loc[chunk.entity_type.str.lower() == "area", "entity_subtype"].value_counts().to_dict())
                residential_subtypes.update(chunk.loc[(chunk.entity_type.str.lower() == "area") &
                                                       (chunk.unit_usage == "RESIDENTIAL"), "entity_subtype"].value_counts().to_dict())
                openings = chunk.loc[(chunk.entity_type == "opening") & (chunk.unit_usage == "RESIDENTIAL")]
                for kind, selected in openings.groupby("entity_subtype"):
                    # Opening polygons are generally rectangles. Long side is clear span;
                    # short side is wall depth. This measures geometry, not access compliance.
                    for geom in from_wkt(selected.geometry.to_numpy()):
                        rectangle = geom.minimum_rotated_rectangle
                        if rectangle.geom_type == "Polygon" and not rectangle.is_empty:
                            coords = np.asarray(rectangle.exterior.coords)
                            lengths = np.linalg.norm(np.diff(coords, axis=0), axis=1)
                            opening_dimensions[kind].append(float(lengths.max()))
        schema = pd.DataFrame([{"column": key, "observed_dtypes": "/".join(sorted(value))} for key, value in dtypes.items()])
        statistics[basename] = {"rows": count, "columns": len(dtypes)}
        schema.assign(config_hash=digest).to_csv(f"reports/schemas/D1_{basename[:-4]}_columns.csv", index=False)
        write_json(f"reports/schemas/D1_{basename[:-4]}_examples.json", {"config_hash": digest, "rows": examples})
        sections += [f"## {basename}\n\nRows: {count}. Columns: {len(dtypes)}. All-row inferred dtypes:\n\n" + schema.to_markdown(index=False),
                     f"Five sanitized example rows are in `D1_{basename[:-4]}_examples.json`. Geometry is translated to a local origin and truncated; source identifiers are opaque."]
        if basename == "simulations.csv":
            prefixes = Counter(key.split("_")[0] for key in dtypes if not key.endswith("_id"))
            statistics["simulation_prefixes"] = dict(prefixes)
            sections.append("## Simulation prefixes\n\n" + pd.DataFrame(prefixes.items(), columns=["prefix", "columns"]).to_markdown(index=False))
    frame = pd.DataFrame([{"entity_type": key[0], "entity_subtype": key[1], "n": value}
                          for key, value in sorted(subtype_counts.items())])
    frame.assign(config_hash=digest).to_csv("reports/schemas/D1_entity_counts.csv", index=False)
    statistics["area_subtypes"] = dict(sorted(area_subtypes.items()))
    statistics["residential_area_subtypes"] = dict(sorted(residential_subtypes.items()))
    opening_summary = {kind: {"n": len(values), "median_width_m": float(np.median(values)),
                              "q25_m": float(np.quantile(values, .25)), "q75_m": float(np.quantile(values, .75))}
                       for kind, values in sorted(opening_dimensions.items())}
    write_json("reports/schemas/D1_opening_dimensions.json", {"config_hash": digest, "openings": opening_summary})
    statistics["config_hash"] = digest
    write_json("reports/schemas/D1_summary.json", statistics)
    sections += ["## Entity types and subtypes\n\n" + frame.to_markdown(index=False),
                 "Location and location-rating tables are not extracted or published; they are unnecessary for this study."]
    write_report("D1", digest, sections)


def inspect_d2(root: Path, digest: str) -> None:
    """Inventory all keys and explicitly check the geometry coordinate scale."""
    archive = root / "resplan/ResPlan.zip"
    path = extract_named(archive, "ResPlan.pkl", root / "resplan/extracted/ResPlan.pkl")
    with path.open("rb") as stream:
        plans = read_geometry_pickle(stream)
    keys, types, examples, scaling = Counter(), defaultdict(Counter), [], []
    for plan in tqdm(plans, desc="D2 plans"):
        for key, value in plan.items():
            keys[key] += 1
            types[key][value.geom_type if isinstance(value, BaseGeometry) else type(value).__name__] += 1
        inner = plan.get("inner")
        raw_area = inner.area if isinstance(inner, BaseGeometry) else 0
        declared_area = float(plan.get("net_area", 0))
        source_gross = float(plan.get("area", 0))
        footprint = unary_union([plan[key] for key in ("inner", "wall", "door", "window", "front_door")
                                 if isinstance(plan.get(key), BaseGeometry)])
        gross_scale = math.sqrt(source_gross / footprint.area) if source_gross > 0 and footprint.area > 0 else None
        candidate_scale = math.sqrt(declared_area / raw_area) if raw_area > 0 and declared_area > 0 else None
        scaling.append({"plan_key": "D2:" + opaque(plan.get("id")), "raw_inner_area": raw_area,
                        "released_net_area": declared_area, "candidate_scale_from_net": candidate_scale,
                        "source_gross_area_m2": source_gross, "raw_footprint_area": footprint.area,
                        "candidate_scale_from_gross": gross_scale,
                        "raw_wall_depth": float(plan.get("wall_depth", 0)), "config_hash": digest})
        if len(examples) < 5:
            example = {}
            for key, value in plan.items():
                if isinstance(value, BaseGeometry):
                    example[key] = {"type": value.geom_type, "area_in_source_units": value.area,
                                    "empty": value.is_empty}
                elif key in ("area", "net_area", "wall_depth"):
                    example[key] = float(value)
                elif key == "id":
                    example[key] = opaque(value)
                else:
                    example[key] = {"type": type(value).__name__}
            examples.append(example)
    schema = pd.DataFrame([{"key": key, "present": keys[key], "types": json.dumps(types[key], sort_keys=True)} for key in sorted(keys)])
    scale_frame = pd.DataFrame(scaling)
    scale_frame.to_csv("reports/schemas/D2_scale_audit.csv", index=False)
    write_json("reports/schemas/D2_examples.json", {"config_hash": digest, "rows": examples})
    stats = {"plans": len(plans), "nonpositive_net_area": int((scale_frame.released_net_area <= 0).sum()),
             "nonpositive_gross_area": int((scale_frame.source_gross_area_m2 <= 0).sum()),
             "net_larger_than_gross": int((scale_frame.released_net_area > scale_frame.source_gross_area_m2).sum()),
             "positive_gross_scale_median": float(scale_frame.candidate_scale_from_gross.median()), "config_hash": digest}
    write_json("reports/schemas/D2_summary.json", stats)
    write_report("D2", digest, [f"Plans: {len(plans)}. Restricted unpickling accepted only declared geometry/numeric constructors.",
                 schema.to_markdown(index=False), "Five examples are in `D2_examples.json`.",
                 "## Coordinate-scale audit\n\n" + json.dumps(stats, indent=2),
                 "The raw polygon coordinates must not be assumed to be metres. The released net_area is undocumented and can be nonpositive or exceed the source gross area, so it is not used for calibration. The upstream paper defines area as gross floor area in square metres (Section 4, metadata). The proposed conversion is sqrt(area / area(union(inner, wall, door, window, front_door))). It is an explicit calibration assumption, requiring G1 review; it does not verify the accuracy of the listing's declared area. Nonpositive source gross area or footprint area prevents calibration. Both candidate conversions are exposed in `D2_scale_audit.csv` for audit. Source: https://arxiv.org/html/2508.14006v1 ."])


def inspect_d4(root: Path, digest: str) -> None:
    """Measure field availability and observed product types over all ABO listings."""
    total = has_dimensions = has_type = usable_dimensions = 0
    counts, examples = Counter(), []
    for item in tqdm(listings(root / "abo/abo-listings.tar"), desc="D4 listings", mininterval=5):
        total += 1
        has_dimensions += bool(item.get("item_dimensions"))
        labels = product_types(item)
        has_type += bool(labels)
        counts.update(labels)
        dims = dimensions_m(item)
        usable_dimensions += dims is not None
        if dims and len(examples) < 5 and any(any(word in label for word in ("SOFA", "BED", "TABLE", "DESK", "CHAIR", "SHELF")) for label in labels):
            examples.append({"product_type": labels, "item_dimensions": item["item_dimensions"], "dimensions_m": dims})
    summary = {"listings": total, "with_item_dimensions": has_dimensions, "share_item_dimensions": has_dimensions / total,
               "with_product_type": has_type, "share_product_type": has_type / total,
               "usable_dimension_triples": usable_dimensions, "config_hash": digest}
    frame = pd.DataFrame(sorted(counts.items()), columns=["product_type", "n"])
    frame.assign(config_hash=digest).to_csv("reports/schemas/D4_product_types.csv", index=False)
    write_json("reports/schemas/D4_summary.json", summary)
    write_json("reports/schemas/D4_examples.json", {"config_hash": digest, "rows": examples})
    write_report("D4", digest, ["## Coverage\n\n" + json.dumps(summary, indent=2),
                 "## Fields\n\n`item_dimensions` is a dict of width, length and height records; each has value/unit and may have normalized_value. `product_type` is a list of value records. Listing length is mapped to depth; unknown or missing units are not guessed. Product IDs, titles, contact fields and media links are omitted.",
                 "## Observed product types\n\n" + frame.to_markdown(index=False), "Five furniture examples are in `D4_examples.json`."])


def inspect_d6(root: Path, digest: str) -> None:
    """Use the source CSV header dictionary and locate the relevant PDF definitions."""
    table, meanings, notes = census_table(root / "hk_census/DC_21C_SDU.zip")
    fields = pd.DataFrame([{"field": key, "dtype": str(table[key].dtype), "meaning": value} for key, value in meanings.items()])
    table.assign(config_hash=digest).to_csv("reports/schemas/D6_data.csv", index=False)
    reader = PdfReader(root / "hk_census/data_dictionary.pdf")
    hits, text_characters, empty_pages = [], 0, 0
    private = Path("data/interim/d6_dictionary")
    private.mkdir(parents=True, exist_ok=True)
    for index, page in enumerate(tqdm(reader.pages, desc="D6 dictionary", mininterval=5)):
        text = page.extract_text() or ""
        text_characters += len(text)
        empty_pages += not bool(text.strip())
        if "subdividedunits" in re.sub(r"[^a-z]", "", text.lower()):
            hits.append(index + 1)
            (private / f"page_{index+1:03d}.txt").write_text(text, encoding="utf-8")
    summary = {"rows_including_territory_total": len(table), "pdf_pages": len(reader.pages),
               "dictionary_subdivided_pages": hits, "household_size_distribution_available": False,
               "dictionary_extracted_characters": text_characters, "dictionary_empty_text_pages": empty_pages,
               "floor_area_distribution_available": False, "config_hash": digest}
    write_json("reports/schemas/D6_summary.json", summary)
    write_report("D6", digest, ["## Fields and source-supplied meanings\n\n" + fields.to_markdown(index=False),
                 "## First five rows\n\n" + table.head(5).to_markdown(index=False),
                 "## Coverage\n\n" + json.dumps(summary, indent=2),
                 "The CSV contains district aggregates and a territory total, not household-size or dwelling-area distributions. These distributions cannot be inferred from the four count columns. The CSV source note defines an SDU through subdivision into internally connected and externally accessible units. Personal contact fields in the footer are not reproduced. The linked general IDDS dictionary is inspected in full; if it lacks SDU entries, the official CSV's bilingual field definitions and notes supply the specific dictionary instead. Dictionary page hits, if any, are retained as local review evidence."])


def main() -> None:
    """Run one or all data inspections, retaining explicit partial-run status."""
    parser = prepare_cli(__doc__)
    parser.add_argument("--datasets", nargs="+", choices=["D1", "D2", "D4", "D6"], default=["D1", "D2", "D4", "D6"])
    args = parser.parse_args()
    config, digest, start = start_run(args, "02_inspect_schemas")
    if args.dry_run:
        print("Would inspect: " + ", ".join(args.datasets))
        return
    Path("reports/schemas").mkdir(parents=True, exist_ok=True)
    functions = {"D1": inspect_d1, "D2": inspect_d2, "D4": inspect_d4, "D6": inspect_d6}
    for dataset in args.datasets:
        dataset_start = time.perf_counter()
        functions[dataset](Path(config["paths"]["raw"]), digest)
        write_json(f"reports/schema_runs/{dataset}.json", {"dataset": dataset, "config_hash": digest,
                   "os": platform.system(), "python": platform.python_version(),
                   "runtime_s": round(time.perf_counter() - dataset_start, 3)})
    write_json("reports/schema_run.json", {"datasets": args.datasets, "partial": len(args.datasets) != 4,
                                          "os": platform.system(), "python": platform.python_version(),
                                          "config_hash": digest, "runtime_s": round(time.perf_counter() - start, 3)})


if __name__ == "__main__":
    main()
