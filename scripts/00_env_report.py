"""Record reproducible software and capacity facts without machine identifiers."""
from __future__ import annotations

import importlib.metadata
import math
import os
import platform
import subprocess
import sys
import time
from pathlib import Path

import requests
from tqdm import tqdm

from fea.io import prepare_cli, start_run, write_json


def capture(command: list[str]) -> str:
    """Capture a bounded command; do not publish command paths or tracebacks."""
    try:
        result = subprocess.run(command, capture_output=True, text=True, timeout=30)
        return result.stdout.strip() if result.returncode == 0 else "unavailable"
    except (OSError, subprocess.TimeoutExpired):
        return "unavailable"


def main() -> None:
    """Generate the privacy-filtered environment report and package lock."""
    args = prepare_cli(__doc__).parse_args()
    _, digest, start = start_run(args, "00_environment")
    if args.dry_run:
        print("Would inspect environment and write sanitized reports plus dependency lock.")
        return
    facts = {"config_hash": digest, "os": platform.system(), "machine_architecture": platform.machine(),
             "python": platform.python_version()}
    for label in tqdm(["hardware", "network", "packages", "checks"], desc="Environment"):
        if label == "hardware":
            cpuinfo = Path("/proc/cpuinfo")
            facts["cpu_model"] = next((line.split(":", 1)[1].strip() for line in cpuinfo.read_text().splitlines()
                                       if line.startswith("model name")), "unknown") if cpuinfo.exists() else platform.processor()
            affinity = len(os.sched_getaffinity(0)) if hasattr(os, "sched_getaffinity") else os.cpu_count()
            quota_path = Path("/sys/fs/cgroup/cpu.max")
            quota = quota_path.read_text().split() if quota_path.exists() else ["max"]
            effective = affinity if quota[0] == "max" else max(1, min(affinity, math.floor(int(quota[0]) / int(quota[1]))))
            facts.update(affinity_cores=affinity, effective_cores=effective)
            mem = Path("/sys/fs/cgroup/memory.max")
            limit = mem.read_text().strip() if mem.exists() else "max"
            facts["memory_limit_gib"] = round(int(limit) / 2**30, 3) if limit.isdigit() else None
            facts["gpu"] = capture(["nvidia-smi", "--query-gpu=name,memory.total,driver_version", "--format=csv,noheader"])
        elif label == "network":
            facts["network"] = {}
            for name, url in {"D1": "https://zenodo.org/records/7788422", "D2": "https://github.com/m-agour/ResPlan",
                              "D4": "https://amazon-berkeley-objects.s3.amazonaws.com/index.html",
                              "D6": "https://www.census2021.gov.hk"}.items():
                try:
                    with requests.get(url, timeout=20, stream=True) as response:
                        facts["network"][name] = {"http_status": response.status_code}
                except requests.RequestException as exc:
                    facts["network"][name] = {"error": type(exc).__name__}
        elif label == "packages":
            # pip freeze emits the absolute editable checkout; exclude that line.
            packages = sorted({f"{d.metadata['Name']}=={d.version}" for d in importlib.metadata.distributions()
                               if d.metadata['Name'].lower() != "fea-research"}, key=str.lower)
            Path("requirements.lock.txt").write_text("\n".join(packages) + "\n", encoding="utf-8")
        else:
            facts["imports"] = capture([sys.executable, "-c", "import ortools, shapely; print('PASS')"])
            test = subprocess.run([sys.executable, "-m", "pytest", "-q"], capture_output=True, text=True)
            facts["pytest_exit_code"] = test.returncode
            # Record test summary without paths or traceback details.
            facts["pytest_summary"] = test.stdout.strip().splitlines()[-1] if test.stdout.strip() else "no output"
    facts["runtime_s"] = round(time.perf_counter() - start, 3)
    write_json("reports/environment.json", facts)
    rows = "\n".join(f"| {key} | {value} |" for key, value in facts.items() if key != "network")
    network = "\n".join(f"- {name}: {status}" for name, status in facts["network"].items())
    Path("reports/ENVIRONMENT.md").write_text(
        "# Environment\n\nGenerated by `scripts/00_env_report.py`. Machine location, identifiers, users and paths are omitted.\n\n"
        f"| Property | Measured value |\n|---|---|\n{rows}\n\n## Outbound data-source checks\n{network}\n\n"
        "The GPU is not required for Phases 0–4. Dependencies are in `requirements.lock.txt`; "
        "install the local package separately with `python -m pip install -e . --no-deps`.\n", encoding="utf-8")
    print({k: facts[k] for k in ("python", "effective_cores", "memory_limit_gib", "imports", "pytest_exit_code")})


if __name__ == "__main__":
    main()
